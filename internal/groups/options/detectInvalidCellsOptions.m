classdef detectInvalidCellsOptions < baseOptions
% DETECTINVALIDCELLSOPTIONS Options for detecting invalid cells based on
% their fluorescence (wether they ahve NaNs)
%   Class containing the options for dying cells detection
%
%   Copyright (C) 2016-2015, Javier G. Orlandi <javier.orlandi@ucalgary.ca>
%
%   See also detectInvalidCells, baseOptions, optionsWindow

  properties
    % Group to perform function on:
    % - none: will use all traces
    % - all: will recursively go through all defined groups
    % - group parent: will iterate through all the group submembers
    % - group member: will only use the members of this group
    group = {'none', ''};
    
    
    % Type of traces to use
    traces = {'raw', 'smoothed'};
  end
  methods
    function obj = setExperimentDefaults(obj, experiment)
      if(~isempty(experiment) && isstruct(experiment))
        try
          obj.group = getExperimentGroupsNamesFull(experiment);
        catch ME
          logMsg(strrep(getReport(ME), sprintf('\n'), '<br/>'), 'e');
        end
      elseif(~isempty(experiment) && exist(experiment, 'file'))
        exp = load(experiment, '-mat', 'folder', 'name', 'traceGroups', 'traceGroupsNames');
        groups = getExperimentGroupsNamesFull(exp);
        if(~isempty(groups))
          obj.group = groups;
        end
        if(length(obj.group) == 1)
          obj.group{end+1} = '';
        end
      end
    end
  end
end
